# Load dataset
df = pd.read_csv('portfolio_data.csv')
# Use .iloc for index slicing of assets and weights as there is clean, aligned data
asset_ids = df.iloc[:,0].astype(str).values
weights = df.iloc[:,1].astype(float).values
# Conduct index slicing from column two onwards so that we only extract asset prices
price_matrix = df.iloc[:,2:].astype(float).values

# Define a function to calculate the annual covariance matrix
def calc_annual_covmat(price_matrix):
# Calculate returns matrix via returns formula of Rt = (Pt - P(t-1))/ P(t-1) for each time stamp
  returns_matrix = np.diff(price_matrix, axis = 1) / price_matrix[:, :-1]
  R = returns_matrix
# Calculate the monthly covariance matrix clearly stating that rows are variables
  cov_matrix_monthly = np.cov(R, rowvar = True)
# Annualise the covariance matrix by 12 as time stamps are monthly
  cov_matrix_annual = cov_matrix_monthly * 12
  return cov_matrix_annual

# Define a funciton to calculate volatility of assets and the total portfolio
def calc_vol(cov_matrix_annual, weights):
# Use the diagonals which represent variance values and square root to get volatility of individual assets
  asset_vol = np.sqrt(np.diag(cov_matrix_annual))
# Use portfolio equation w^t * Cov * w for calculation
  portfolio_var = np.dot(weights.T, np.dot(cov_matrix_annual, weights))
  portfolio_vol = np.sqrt(portfolio_var)
  return asset_vol, portfolio_vol

# Calculate annual covariance matrix and individual asset volatilities
cov_matrix_annual = calc_annual_covmat(price_matrix)
asset_vol, portfolio_vol = calc_vol(cov_matrix_annual, weights)

# Define a function to calculate contribution to portfolio volatility of each asset
def calc_ctr(weights, cov_matrix_annual, portfolio_vol):
# Calculate the marginal contribution of each asset towards portfolio volatility
  marg_contribution = np.dot(cov_matrix_annual, weights)
# Use Euler's theorem to calculate contribution to volatility
  ctr = (weights * marg_contribution) / portfolio_vol
  return ctr

# Calculate contribution to portfolio volatility
ctr = calc_ctr(weights, cov_matrix_annual, portfolio_vol)

# Print the portfolio volatility to 2dp
print(f"Total Portfolio Volatility: {portfolio_vol:.2%}")
# Print the asset id, weight, volatility and CTR with sufficient spacing
print(f"{'Asset ID':<20} | {'Weight':<8} | {'Volatility':<12} | {'CTR':<10}")
print("-" * 55)
# Write a loop to print these values for every asset
for id_, w, vol, c in zip(asset_ids, weights, asset_vol, ctr):
    print(f"{id_:<20} | {w:>7.2%} | {vol:>10.2%} | {c:>8.2%}")

print("-" * 55)

# Confirm that volatility matches initial value
print("-" * 55)
print(f"Sum of Asset CTRs: {np.sum(ctr):.2%}")
